/* El check vive DENTRO del punto elegido, así que al cambiar de punto hay que
   mudarlo; clonar dejaría dos. */
function moveSel(list, el, keepChild){
  list.forEach(function(x){
    if(x===el) return;
    x.classList.remove('sel');
    if(keepChild){ const c=x.querySelector('svg:not(.plk)'); if(c) c.remove(); }
  });
  el.classList.add('sel');
}

const dots = [].slice.call(document.querySelectorAll('.dot-grid .dot'));
const check = document.querySelector('.dot-grid .dot.sel svg:not(.plk)');
dots.forEach(function(dot){
  const c = (dot.style.getPropertyValue('--d')||'').trim();
  if(!c) return;                       /* el arcoíris no es un color plano */
  dot.style.cursor = 'pointer';
  dot.setAttribute('role','button');
  dot.setAttribute('tabindex','0');
  function pick(){
    root.style.setProperty('--green', c);
    moveSel(dots, dot, true);
    if(check && !dot.contains(check)) dot.appendChild(check);
    try{ localStorage.setItem('atreus_accent', c); }catch(e){}
  }
  dot.addEventListener('click', pick);
  dot.addEventListener('keydown', function(e){ if(e.key==='Enter'||e.key===' '){ e.preventDefault(); pick(); } });
});

const thms = [].slice.call(document.querySelectorAll('.theme-grid .thm'));
thms.forEach(function(thm, i){
  const id = SKIN_ORDER[i];
  if(!id) return;
  thm.style.cursor = 'pointer';
  thm.setAttribute('role','button');
  thm.setAttribute('tabindex','0');
  function pick(){
    applySkin(id);
    moveSel(thms, thm, false);
    try{ localStorage.setItem('atreus_skin', id); }catch(e){}
  }
  thm.addEventListener('click', pick);
  thm.addEventListener('keydown', function(e){ if(e.key==='Enter'||e.key===' '){ e.preventDefault(); pick(); } });
});

function applySkin(id){
  const skin = SKINS[id]; if(!skin) return;
  for(const k in skin) root.style.setProperty(k, skin[k]);
  /* La foto del héroe y los marcos de móvil son oscuros de fábrica: en tema claro
     hay que bajarles la mano o el resto de la página parece de otra web. */
  root.classList.toggle('lightskin', LIGHT_SKINS.indexOf(id) >= 0);
}

